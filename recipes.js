// ПП-замены: обычный ингредиент → полезная альтернатива (без глютена, без лактозы, без сахара).
// Правила проверяются по названию ингредиента (до « — »), количество остаётся прежним.
const PP_RULES = [
  [/ванильный сахар/i, 'ванилин'],
  [/сахарная пудра/i, 'пудра из эритрита'],
  [/сахар( коричневый)?/i, 'эритрит'],
  [/мука/i, 'безглютеновая мука'],
  [/овсяные хлопья/i, 'овсяные хлопья без глютена'],
  [/гранола/i, 'гранола без сахара и глютена'],
  [/батон или бриошь|хлеб цельнозерновой/i, 'безглютеновый хлеб'],
  [/булочки для бургеров/i, 'безглютеновые булочки'],
  [/спагетти/i, 'безглютеновые спагетти'],
  [/пенне/i, 'безглютеновые пенне'],
  [/соевый соус/i, 'соус тамари без глютена'],
  [/(?<!кокосовое )молоко/i, 'безлактозное молоко'],
  [/сливки/i, 'безлактозные сливки'],
  [/сливочное масло( мягкое)?/i, 'топлёное масло гхи'],
  [/творог/i, 'безлактозный творог'],
  [/греческий йогурт/i, 'безлактозный греческий йогурт'],
  [/майонез/i, 'греческий йогурт'],
  [/маскарпоне/i, 'безлактозный сливочный сыр'],
  [/моцарелла/i, 'безлактозная моцарелла'],
  [/сыр чеддер/i, 'безлактозный чеддер'],
  [/сыр или фета|фета/i, 'безлактозная фета'],
  [/шоколадные капли/i, 'горький шоколад 70%'],
  [/соус барбекю/i, 'соус барбекю без сахара'],
  [/гуанчиале или бекон/i, 'бекон из индейки'],
  [/20% жирности/i, '10% жирности']
];

// Возвращает { name, rest, pp } — pp есть, только если хоть одно правило сработало
function ppSwap(ingredient) {
  const i = ingredient.indexOf(' — ');
  const name = i < 0 ? ingredient : ingredient.slice(0, i), rest = i < 0 ? '' : ingredient.slice(i);
  let pp = name;
  for (const [re, to] of PP_RULES) pp = pp.replace(re, to);
  if (pp === name) return { name, rest, pp: null };
  return { name, rest, pp: pp[0].toUpperCase() + pp.slice(1) };
}

// Пересчёт количества на другое число порций: k = новые порции / порции рецепта.
// Меняются только числа после « — »; «по 150 г» после другого числа (2 стейка по 150 г) не трогаем.
const FRACTIONS = { '½': .5, '¼': .25, '¾': .75 };
const WORD_FORMS = { 'зубчик': ['зубчик', 'зубчика', 'зубчиков'], 'ломтик': ['ломтик', 'ломтика', 'ломтиков'],
  'веточк': ['веточка', 'веточки', 'веточек'], 'стейк': ['стейк', 'стейка', 'стейков'] };
const toNum = s => FRACTIONS[s] ?? parseFloat(s.replace(',', '.'));
function fmtQty(v, unit) {
  if (unit === 'г' || unit === 'мл') return String(v >= 100 ? Math.round(v / 10) * 10 : v >= 20 ? Math.round(v / 5) * 5 : Math.max(1, Math.round(v)));
  if (unit === 'кг') return String(Math.round(v * 10) / 10).replace('.', ',');
  v = v < 1 ? Math.max(.25, Math.round(v * 4) / 4) : Math.round(v * 2) / 2;
  if (v < 1) return { .25: '¼', .5: '½', .75: '¾' }[v];
  return String(v).replace('.', ',');
}
function wordForm(stem, v) {
  const f = WORD_FORMS[stem]; if (!f) return stem;
  if (v % 1) return f[1];
  const n = v % 100, d = n % 10;
  return n > 10 && n < 20 ? f[2] : d === 1 ? f[0] : d >= 2 && d <= 4 ? f[1] : f[2];
}
function scaleQty(rest, k) {
  if (k === 1 || !rest) return rest;
  let seen = false;
  return rest.replace(/(по )?(\d+(?:,\d+)?|[½¼¾])(?:–(\d+(?:,\d+)?))?( ?)(г|мл|кг|%|(зубчик|ломтик|веточк|стейк)[а-я]*)?/g,
    (m, po, a, b, sp, unit = '', stem) => {
      if (unit === '%' || (po && seen)) return m;
      seen = true;
      const u = stem ? '' : unit, hi = toNum(b ?? a) * k;
      const num = fmtQty(toNum(a) * k, u) + (b ? '–' + fmtQty(hi, u) : '');
      return (po || '') + num + sp + (stem ? wordForm(stem, toNum(fmtQty(hi, u).replace(/[½¼¾]/, x => FRACTIONS[x]))) : unit);
    });
}
